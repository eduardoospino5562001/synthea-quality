_KEYS = frozenset(entry.key for entry in SOCIAL_CODES)


def is_social(system: str | None, code: str) -> bool:
    """Whether ``(system, code)`` is on the list; a missing system matches by code alone."""
    if system is None:
        return any(code == entry.code for entry in SOCIAL_CODES)
    return (normalise_system(system), code) in _KEYS


def describe_list() -> dict[str, Any]:
    """The list's identity and provenance, as recorded in a report."""
    return {
        "id": SOCIAL_LIST_ID,
        "source": "built-in",
        "synthea_commit": SYNTHEA_COMMIT,
        "source_modules": list(SOURCE_MODULES),
        "codes": len(SOCIAL_CODES),
        "entries": [
            {
                "system": entry.system,
                "code": entry.code,
                "display": entry.display,
                "modules": list(entry.modules),
            }
            for entry in SOCIAL_CODES
        ],
    }
