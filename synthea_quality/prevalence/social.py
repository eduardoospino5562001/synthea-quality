"""[PREVALENCE] Social and administrative condition codes, versioned and attributed.

Synthea writes some codes to ``conditions.csv`` that are not diseases: the answers of the
social determinants of health screening (employment, education, stress, social isolation,
violence, housing, transport…) and an administrative marker (``Medication review due``).
In the sample they head the list of the most common conditions, so a general prevalence
table would open with employment status instead of disease.

The general table leaves them out **by default** and says so; ``--include-social`` puts
them back. Conditions asked for by code are never filtered. If the Synthea maintainers
advise otherwise, only this list or that default changes.

How the list is built
---------------------
Not from the SNOMED semantic tag: ``(finding)`` would also remove clinical findings such
as Prediabetes and obesity, and would keep ``Medication review due (situation)`` and
``Refugee (person)``. Instead, the list is every code a ``ConditionOnset`` state writes
in two modules, extracted mechanically by ``scripts/extract_social_codes.py`` from
Synthea commit ``d9d07a6e`` (the commit that generated the official sample; the modules
are unchanged at ``44f645c``):

* ``encounter/sdoh_hrsn.json`` — "SDoH HRSN" screening (20 codes);
* ``med_rec.json`` — "Medication Reconciliation" (1 code).

Each entry records every module that writes the code, so a code shared with another
module (``Homeless`` with ``homelessness.json``, ``Victim of intimate partner abuse``
with ``hark_screening.json``) shows it. Substance use and anxiety screening findings are
clinical and stay in the table.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from synthea_quality.prevalence.models import normalise_system

#: Identifier of this version of the list, recorded in every report.
SOCIAL_LIST_ID = "synthea-d9d07a6e-social-1"
#: Synthea commit the list was extracted from.
SYNTHEA_COMMIT = "d9d07a6e"
#: Modules whose condition codes form the list.
SOURCE_MODULES = ("encounter/sdoh_hrsn.json", "med_rec.json")


@dataclass(frozen=True, slots=True)
class SocialCode:
    """One code of the list, with the module files that write it."""

    code: str
    display: str
    system: str
    modules: tuple[str, ...]

    @property
    def key(self) -> tuple[str | None, str]:
        return normalise_system(self.system), self.code


